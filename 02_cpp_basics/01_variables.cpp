#include <iostream>
using namespace std;

int main() {

    // Variable names are case-sensitive
    
    int age;        // lowercase
    int Age;        // uppercase A
    int AGE2;       // uppercase letters + digit
    int age_2;      // underscore between characters
    int _age_2;     // starts with an underscore
    
    // age, Age, and AGE are three different variables
    // Variable names can contain letters, digits, and underscore (_), ---->
   // ----> but cannot start with a digit, contain spaces/special characters, or be a C++ keyword.

    return 0;
}
